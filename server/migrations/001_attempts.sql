CREATE TABLE IF NOT EXISTS olympiad_attempts (
  sid VARCHAR(100) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
  test_id VARCHAR(20) CHARACTER SET ascii NOT NULL,
  surname VARCHAR(60) NOT NULL,
  given_name VARCHAR(60) NOT NULL,
  email VARCHAR(100) NOT NULL,
  answers JSON NOT NULL,
  payload JSON NOT NULL,
  payload_hash CHAR(64) CHARACTER SET ascii NOT NULL,
  started_at DATETIME(3) NOT NULL,
  finished_at DATETIME(3) NOT NULL,
  duration_seconds INT UNSIGNED NOT NULL,
  auto_finished BOOLEAN NOT NULL,
  audio_plays TINYINT UNSIGNED NOT NULL,
  lang VARCHAR(2) NOT NULL,
  user_agent VARCHAR(200) NOT NULL,
  score_total INT UNSIGNED NOT NULL,
  score_max INT UNSIGNED NOT NULL,
  score_parts JSON NOT NULL,
  score_per_question JSON NOT NULL,
  scoring_version CHAR(64) CHARACTER SET ascii NOT NULL,
  google_sheet VARCHAR(50) NOT NULL,
  sync_status ENUM('pending','syncing','synced','failed') NOT NULL DEFAULT 'pending',
  sync_attempts INT UNSIGNED NOT NULL DEFAULT 0,
  sync_last_attempt_at DATETIME(3) NULL,
  sync_next_attempt_at DATETIME(3) NULL,
  sync_lease_until DATETIME(3) NULL,
  sync_token CHAR(36) CHARACTER SET ascii NULL,
  sync_error VARCHAR(2000) NULL,
  sync_response JSON NULL,
  synced_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX sync_queue (sync_status, sync_next_attempt_at, sync_lease_until),
  INDEX test_created (test_id, created_at),
  INDEX email_lookup (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
